interface ITKCharacterTrait {
   name: () => string;
   icon: string;
}

export const TKCharacterTraits = {
   Civil: { name: () => "Civil", icon: "feed" },
   Martial: { name: () => "Martial", icon: "swords" },
} as const satisfies Record<string, ITKCharacterTrait>;
export type TKCharacterTrait = keyof typeof TKCharacterTraits;

export const TKCharacterTier = {
   Tier1: () => "S",
   Tier2: () => "A",
   Tier3: () => "B",
   Tier4: () => "C",
} as const satisfies Record<string, () => string>;

export type TKCharacterTier = keyof typeof TKCharacterTier;

export function getTKCharacterTierToSkill(tier: TKCharacterTier): number {
   switch (tier) {
      case "Tier1":
         return randInt(5, 7); // 5-6
      case "Tier2":
         return randInt(4, 6); // 4-5
      case "Tier3":
         return randInt(3, 6); // 3-5
      case "Tier4":
         return randInt(3, 5); // 3-4
      default:
         tier satisfies never;
         return GovernorMinIncl;
   }
}

